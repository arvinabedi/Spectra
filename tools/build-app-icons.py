#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/build-app-icons.py — ساختِ نشانِ Spectra برای همهٔ سطح‌ها
=====================================================================
چرا این فایل وجود دارد:
    نشانِ برنامه پیش از این سه شکلِ متفاوت داشت — بالنِ آزمایشگاهی در
    نوارِ کنار، بالنی دیگر با آبیِ فیروزه‌ای روی سرمه‌ای برای favicon، و
    یک حلقهٔ بنزنِ درخشان برای لانچرِ اندروید. هیچ‌کدام نه پالت مشترکی
    داشتند نه زبانِ ترسیمی مشترکی با هفت آیکونِ مرحله‌ها.

    بدتر از ناهماهنگی: نشانِ نوارِ کنار دقیقاً همان گلیفِ آیکونِ مرحلهٔ ۶
    («آنالیز کلاسیک») بود، یعنی برند مثل یکی از بخش‌های خودِ برنامه
    خوانده می‌شد — و آن هم بخشی که Spectra کمتر از همه دربارهٔ آن است.

    حالا یک هندسه هست و از همین‌جا برای همهٔ سطح‌ها تولید می‌شود، پس
    دیگر نسخه‌های PNG نمی‌توانند از هم جدا بیفتند. نشان همان مفهومِ
    آیکونِ قدیمیِ اندروید را نگه می‌دارد — طیفی که به ساختار می‌رسد — ولی
    با زبانِ خودِ برنامه: خطِ تخت، بدونِ درخش، بدونِ شیب.
    قلهٔ میانیِ طیف دقیقاً به رأسِ پایینیِ حلقه می‌رسد، پس دو نیمه یک
    شکل‌اند نه دو تصویرِ روی‌هم.

اجرا:  python tools/build-app-icons.py
       (نیازمندِ Pillow؛ خروجی‌ها را مستقیم روی res/ می‌نویسد)
سپس:  node tools/build-android.js   تا در APK بنشیند.

نکتهٔ تاریخی: لایهٔ رویی قبلی «آلفازدایی‌شده» روی ‎#0e0b2c بود و به همین
دلیل پس‌زمینه باید دقیقاً همان رنگ می‌ماند. لایهٔ تازه پس‌زمینهٔ شفافِ
واقعی دارد، پس آن قید برداشته شد و رنگِ پس‌زمینه آزاد است.
"""

import os
import sys
from PIL import Image, ImageDraw

# کنسولِ ویندوز پیش‌فرض cp1252 است و روی نخستین پیامِ فارسی می‌شکند.
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

# ---------------------------------------------------------------------
# پالت — از همان توکن‌های css/styles.css
# ---------------------------------------------------------------------
INDIGO = (75, 82, 217, 255)      # --accent  #4b52d9
WHITE = (255, 255, 255, 255)

# ---------------------------------------------------------------------
# هندسهٔ نشان، در دستگاهِ ۳۲ واحدی (همان viewBox که در index.html هست)
#   • شش‌ضلعیِ رأس‌بالا، هم‌هندسه با آیکونِ مرحلهٔ ۲ (حلقهٔ کربنی)
#   • دایرهٔ درونی = نمادِ آروماتیک
#   • خطِ طیف که قلهٔ میانی‌اش روی رأسِ پایینیِ حلقه می‌ایستد
# ---------------------------------------------------------------------
#
# دو چیز در نسخهٔ نخست غلط از آب درآمد و اینجا اصلاح شده:
#   • قلهٔ میانی تا رأسِ پایینیِ حلقه بالا می‌آمد. روی کاغذ «طیفی که به
#     ساختار می‌رسد» بود، ولی رستر‌شده حلقه انگار روی دو پا ایستاده بود
#     و کل نشان مثل یک حشره خوانده می‌شد. حالا فاصلهٔ روشنی هست: طیف
#     زیرِ ساختار می‌نشیند، به آن نمی‌چسبد.
#   • دایرهٔ آروماتیک با شعاعِ ۳٫۱ در حلقه‌ای به شعاعِ ~۷٫۶ آن‌قدر کوچک
#     بود که مثل چشم دیده می‌شد. نسبتِ متعارفِ نمادِ آروماتیک ~۵۵٪ شعاعِ
#     حلقه است؛ حالا همان است.
HEX = [(16, 3.0), (22.58, 6.8), (22.58, 14.4), (16, 18.2), (9.42, 14.4), (9.42, 6.8)]
RING_C, RING_R = (16, 10.6), 4.1
SPECTRUM = [(3, 28), (8.6, 28), (10.9, 22.4), (13.2, 28), (14.4, 28),
            (16, 21.0), (17.6, 28), (18.8, 28), (21.1, 22.4), (23.4, 28), (29, 28)]

W_HEX = 1.45      # وزنِ خط، هم‌خانوادهٔ ۱٫۷ آیکون‌های مرحله‌ها
W_RING = 1.15

# جعبهٔ محیطیِ کلِ ترسیم، برای جای‌دادنِ دقیق در ناحیهٔ امن
BOX_X0, BOX_X1 = 3.0, 29.0
BOX_Y0, BOX_Y1 = 3.0, 28.0
BOX_CX = (BOX_X0 + BOX_X1) / 2
BOX_CY = (BOX_Y0 + BOX_Y1) / 2
BOX_W = BOX_X1 - BOX_X0

SS = 4           # نمونه‌برداریِ فوق‌العاده، برای لبه‌های نرم


def _round_caps(d, pts, w, color):
    """Pillow سرِ خطِ گرد ندارد؛ با دایره‌های کوچک ساخته می‌شود."""
    r = w / 2.0
    for x, y in pts:
        d.ellipse([x - r, y - r, x + r, y + r], fill=color)


def _polyline(d, pts, w, color, closed=False):
    seq = list(pts) + ([pts[0]] if closed else [])
    d.line(seq, fill=color, width=max(1, int(round(w))), joint="curve")
    _round_caps(d, seq, w, color)


def render(size, color, artwork_frac):
    """نشان را روی بومِ شفافِ مربعی به اندازهٔ size می‌کشد.

    artwork_frac نسبتِ عرضِ ترسیم به عرضِ بوم است. برای آیکونِ سازگارِ
    اندروید ۰٫۵۷ گرفته شده: روی بومِ ۱۰۸dp یعنی ~۶۲dp، که با فاصلهٔ
    مطمئن داخلِ ناحیهٔ امنِ ۷۲dp می‌ماند و زیرِ ماسکِ دایره‌ای هم بریده
    نمی‌شود.
    """
    n = size * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    s = (n * artwork_frac) / BOX_W          # پیکسل به ازای هر واحد
    cx = cy = n / 2.0
    T = lambda p: (cx + (p[0] - BOX_CX) * s, cy + (p[1] - BOX_CY) * s)

    _polyline(d, [T(p) for p in HEX], W_HEX * s, color, closed=True)
    _polyline(d, [T(p) for p in SPECTRUM], W_HEX * s, color)

    rc, rr = T(RING_C), RING_R * s
    d.ellipse([rc[0] - rr, rc[1] - rr, rc[0] + rr, rc[1] + rr],
              outline=color, width=max(1, int(round(W_RING * s))))

    return img.resize((size, size), Image.LANCZOS)


def write(img, *parts):
    p = os.path.join(*parts)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    img.save(p, "PNG")
    print("  " + os.path.relpath(p, ROOT).replace("\\", "/") + "  " + str(img.size[0]) + "px")


def main():
    # لایهٔ رویی و تک‌رنگِ آیکونِ سازگار — بومِ ۱۰۸dp در پنج چگالی
    DENSITIES = [("mdpi", 108), ("hdpi", 162), ("xhdpi", 216),
                 ("xxhdpi", 324), ("xxxhdpi", 432)]
    print("لایهٔ رویی (سفید روی شفاف):")
    for name, px in DENSITIES:
        write(render(px, WHITE, 0.57), RES, "drawable-" + name, "ic_launcher_foreground.png")
    # تک‌رنگ برای آیکونِ هم‌رنگِ اندروید ۱۳ — سیستم خودش رنگش می‌کند،
    # پس فقط شکل مهم است.
    print("تک‌رنگ (اندروید ۱۳):")
    for name, px in DENSITIES:
        write(render(px, WHITE, 0.57), RES, "drawable-" + name, "ic_launcher_monochrome.png")

    # آیکونِ فروشگاه: مربعِ پُرِ نیلی، چون خودِ فروشگاه گوشه‌ها را گرد می‌کند
    print("آیکونِ فروشگاه:")
    store = Image.new("RGBA", (512, 512), INDIGO)
    store.alpha_composite(render(512, WHITE, 0.57))
    write(store.convert("RGB"), ROOT, "android", "play-store-icon-512.png")


if __name__ == "__main__":
    main()
